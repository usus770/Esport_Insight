export const getItemImageUrl = (itemId) => {
    const itemName = itemMap[itemId];
    if (!itemName) return null;

    // Handle recipes
    if (itemName.startsWith('recipe')) {
        return `https://cdn.cloudflare.steamstatic.com/apps/dota2/images/dota_react/items/recipe.png`;
    }

    // Use Cloudflare Steam CDN (Verified working)
    return `https://cdn.cloudflare.steamstatic.com/apps/dota2/images/dota_react/items/${itemName}.png`;
};
